import { afterAll, expect, test } from "bun:test";
import { mkdtemp, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { blockPlanSchema } from "../src/types.ts";
import { planHash } from "../src/compose.ts";
import { prepareSaveIntent } from "../src/save-intent.ts";
import { userConfigSchema } from "../src/config.ts";
const directory=await mkdtemp(join(tmpdir(),"arena-bluesky-canonical-"));
afterAll(()=>rm(directory,{recursive:true,force:true}));
const config=userConfigSchema.parse({provenance:{local:false,remoteSnapshot:"none"}});
const options={origin:"cli"as const,initiator:{kind:"human"as const},operation:"publish"as const,destinations:["fixture-inbox"]};
for(const media of ["none","all"]as const)test(`Bluesky -t ${media} normalizes derived facets before hashing and keeps exact source records`,async()=>{
 const ledger=join(directory,`${media}-ledger.json`),configFile=join(directory,"config.json");await Bun.write(configFile,JSON.stringify(config));
 const base=[process.execPath,"--preload",`${import.meta.dir}/fixtures/bluesky-canonical-thread-cli.ts`,"src/cli.ts"];
 const env={...process.env,ARENA_BLOCK_ACCESS_TOKEN:"",ARENA_BSKY_LEDGER:ledger};
 const args=["--media",media,"https://bsky.app/profile/stephango.com/post/3my3fqho7as2e","-t"];
 const output=Bun.spawnSync([...base,"plan",...args,"--json"],{env,stdout:"pipe",stderr:"pipe"});
 expect(output.exitCode,output.stderr.toString()).toBe(0);
 const plan=JSON.parse(output.stdout.toString()),parsed=blockPlanSchema.parse(plan),{hash,...content}=parsed;
 expect(parsed).toEqual(plan);expect(planHash(content)).toBe(hash);
 expect(plan.sources.map((post:any)=>post.id)).toEqual(["3my3fqho7as2e","3my3fqhqsb22e","3my3fqpb2qc2e","3my3ni6snus23"]);
 expect(plan.sources[2].facets[0]).not.toHaveProperty("$type");
 expect(plan.sources[2].atproto.record.facets[0].$type).toBe("app.bsky.richtext.facet");
 expect(plan.sources[2].atproto.record.text).toBe("A linked reference.");
 expect(plan.block.markdown).toContain("[linked reference](<https://example.com/reference>)");
 expect(plan.block.selectedMedia).toEqual(media==="all"?["1.1","2.1","2.2"]:[]);
 expect(prepareSaveIntent(plan,config,options).snapshot.plan).toEqual(plan);
 const dryRun=Bun.spawnSync([...base,"publish",...args,"--to","fixture-inbox","--dry-run","--config",configFile],{env,stdout:"pipe",stderr:"pipe"});
 expect(dryRun.exitCode,dryRun.stderr.toString()).toBe(0);expect(JSON.parse(dryRun.stdout.toString()).snapshot.plan).toEqual(plan);
 expect((await Bun.file(ledger).json()).requests.every((url:string)=>url.startsWith("https://public.api.bsky.app/"))).toBe(true);
 const changed=structuredClone(plan);changed.block.markdown+=" Changed after hashing.";
 expect(()=>prepareSaveIntent(changed,config,options)).toThrow("Plan hash does not match its snapshot");
});
